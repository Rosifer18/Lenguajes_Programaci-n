    public FormularioCitas() {
        initComponents();
        setLocationRelativeTo(null);
        txtHora.addKeyListener(new KeyAdapter() {
            @Override
            public void keyTyped(KeyEvent e) {
                char c = e.getKeyChar();

                // Permitir retroceso (Backspace)
                if (c == '\b') {
                    return;
                }

                // Bloquear si no es un dígito numérico
                if (!Character.isDigit(c)) {
                    e.consume();
                    return;
                }

                String textoActual = txtHora.getText();
                int len = textoActual.length();

                // Autocompletar los dos puntos después de la hora (HH:)
                if (len == 2) {
                    e.consume();
                    txtHora.setText(textoActual + ":" + c);
                } else if (len >= 5) {
                    // Limitar la longitud máxima a 5 caracteres (HH:mm)
                    e.consume();
                }
            }
        });
        
        
    }
    
